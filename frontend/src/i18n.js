/**
 * Helper to fetch localized string by key and BCP-47 language tag
 * @param {string} key - Dictionary key
 * @param {string} langCode - BCP-47 language tag (e.g. 'ta', 'hi', 'en-IN')
 * @returns {string} - Localized string or English fallback
 */
export function t(key, langCode = 'en') {
  const cleanLang = (langCode || 'en').split('-')[0].toLowerCase();
  const dict = TRANSLATIONS[cleanLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}
